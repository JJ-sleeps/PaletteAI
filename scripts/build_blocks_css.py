"""Generate paletteai/static/blocks.css (pixel-art header blocks) from compact pixel maps.

The two blocks are adapted from a Uiverse.io design by Pinparker (third-party). The
original draws every pixel as one box-shadow entry; the maps below reproduce those.
The pop-up character ("Drip", a paint drop) is our own artwork.
Run:  .venv\\Scripts\\python scripts\\build_blocks_css.py
"""
from pathlib import Path

BRICK = ["pppppppppppppppp"] + (["rrrrrrrkrrrrrrrk"] * 2 + ["kkkkkkkkkkkkkkkk"] + ["rrrkrrrrrrrkrrrr"] * 3 + ["kkkkkkkkkkkkkkkk"]
                                + ["rrrrrrrkrrrrrrrk"] * 3 + ["kkkkkkkkkkkkkkkk"] + ["rrrkrrrrrrrkrrrr"] * 3 + ["kkkkkkkkkkkkkkkk"])
QUESTION = [
    ".oooooooooooooo.", "oyyyyyyyyyyyyyyk", "oykyyyyyyyyyykyk", "oyyyyoooooyyyyyk",
    "oyyyookkkooyyyyk", "oyyyookyyookyyyk", "oyyyookyyookyyyk", "oyyyykkyoookyyyk",
    "oyyyyyyookkkyyyk", "oyyyyyyookyyyyyk", "oyyyyyyykkyyyyyk", "oyyyyyyooyyyyyyk",
    "oyyyyyyookyyyyyk", "oykyyyyykkyyykyk", "oyyyyyyyyyyyyyyk", "kkkkkkkkkkkkkkkk",
]
DRIP = [  # original mascot: a paint drop with a face, 11 x 13 pixels
    ".....k.....", "....kbk....", "....kbk....", "...kblbk...", "...kblbk...", "..kblbbbk..", "..kbbbbbk..",
    ".kbwkbwkbk.", ".kbwkbwkbk.", ".kbbbbbbbk.", ".kbbkkkbbk.", "..kbbbbbk..", "...kkkkk...",
]
COLORS = {"p": "#ff9999", "r": "#cc3300", "k": "#000", "o": "#ce3100", "y": "#ff9c31", "b": "#275efe", "l": "#9dbbff", "w": "#fff"}


def shadows(rows):
    assert len({len(r) for r in rows}) == 1, "every row of a sprite must have the same width"
    return ",".join(f"{2 * (x + 1)}px {2 * (y + 1)}px 0 {COLORS[c]}" for y, row in enumerate(rows) for x, c in enumerate(row) if c != ".")


assert len(BRICK) == len(QUESTION) == 16
REST = -(2 * len(DRIP) + 2 - 2) - 4      # lift so the sprite's feet sit on the block's top edge (pop starts at top: 4px)
CSS = f"""/* Pixel-art header blocks. GENERATED by scripts/build_blocks_css.py - edit that file.
   Blocks adapted from a Uiverse.io design by Pinparker (third-party CSS). Changes: laid out
   as a fixed row centred in the header's free space, decorative only (hidden from assistive
   technology), our own pop-up character, no motion for reduced-motion users, hidden when narrow. */
.app-header .brand {{ flex: 0 1 auto; }}                 /* let the free space sit either side of the blocks */
.pixel-blocks {{ position: relative; isolation: isolate; flex: none; width: 104px; height: 36px; margin: 34px auto 0 0; }}
.pixel-blocks .brick, .pixel-blocks .qblock {{ position: absolute; top: 0; height: 2px; width: 2px; }}
.pixel-blocks .brick {{ box-shadow: {shadows(BRICK)}; }}
.pixel-blocks .brick.one {{ left: 0; }}
.pixel-blocks .brick.two {{ left: 68px; }}
.pixel-blocks .qblock {{ left: 34px; box-shadow: {shadows(QUESTION)}; }}
.pixel-blocks .box {{ position: absolute; left: 0; top: 0; z-index: 3; width: 34px; height: 34px; background: transparent; cursor: pointer; }}
.pixel-blocks .pop {{
  position: absolute; left: 5px; top: 4px; width: 2px; height: 2px; z-index: -1; opacity: 0; pointer-events: none;
  box-shadow: {shadows(DRIP)};
}}
.pixel-blocks .box:hover + .pop {{ animation: pop-up .5s linear forwards; opacity: 1; }}
@keyframes pop-up {{
  0% {{ transform: translateY(0); }}
  50% {{ transform: translateY({REST - 14}px); }}
  100% {{ transform: translateY({REST}px); }}
}}
@media (prefers-reduced-motion: reduce) {{ .pixel-blocks .box:hover + .pop {{ animation: none; transform: translateY({REST}px); }} }}
@media (max-width: 900px), print {{ .pixel-blocks {{ display: none; }} }}
"""

out = Path(__file__).resolve().parents[1] / "paletteai" / "static" / "blocks.css"
out.write_text(CSS, encoding="utf-8")
print("wrote", out, len(CSS), "bytes; rest offset", REST)
